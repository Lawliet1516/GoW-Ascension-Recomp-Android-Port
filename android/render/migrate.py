#!/usr/bin/env python3
"""Reproducible analysis of the renderer migration: upstream ps3recomp (pinned) against this fork's ps3kit/libs/video.

Three trees: BASE = the upstream release the fork was cut from (v0.15.0: several fork files are byte-identical to it),
THEIRS = the pinned target (v0.20.0), OURS = the working tree. Needs the refs fetched by android/render/fetch_upstream.sh.
Writes android/render/MIGRATION_ANALYSIS.md. Does not modify any source file."""
import collections, difflib, os, subprocess, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BASE, THEIRS = 'refs/upstream/ps3recomp/v0.15.0', 'refs/upstream/ps3recomp/v0.20.0'
def git(*a, text=True): return subprocess.run(['git', '-C', ROOT, *a], capture_output=True, text=text).stdout
def ls(ref, prefix):
    out = git('ls-tree', '-r', '--format=%(objectname) %(path)', ref, '--', prefix).split('\n')
    return {l.split(' ', 1)[1][len(prefix):].lstrip('/'): l.split(' ', 1)[0] for l in out if l}
def blob(sha): return git('cat-file', 'blob', sha, text=False).decode('utf8', 'replace').split('\n')
def diffsz(a, b): return sum(max(i2 - i1, j2 - j1) for t, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes() if t != 'equal')
def conflicts(path, b, o, t):
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        for n, sha in (('base', b), ('ours', o), ('theirs', t)): open(os.path.join(d, n), 'wb').write(git('cat-file', 'blob', sha, text=False))
        r = subprocess.run(['git', 'merge-file', '-p', os.path.join(d, 'ours'), os.path.join(d, 'base'), os.path.join(d, 'theirs')], capture_output=True)
        return r.returncode
def main():
    base, new, fork = ls(BASE, 'libs/video'), ls(THEIRS, 'libs/video'), ls('HEAD', 'ps3kit/libs/video')
    rows = collections.defaultdict(list)
    for p in sorted(set(base) | set(new) | set(fork)):
        b, n, f = base.get(p), new.get(p), fork.get(p)
        if b is None and f is None: k = 'new in upstream (not in the base, not in the fork)'
        elif b is not None and f is None: k = 'in the base, removed by the fork'
        elif b is None: k = 'added by the fork (Ascension)'
        elif b == f and (n is None or n == b): k = 'identical'
        elif b == f: k = 'fork untouched, upstream changed -> take upstream'
        elif n is None or n == b: k = 'upstream untouched, fork changed -> keep fork'
        else: k = 'changed on both sides -> three-way merge'
        extra = ''
        if k.startswith('changed on both'):
            extra = f"fork +-{diffsz(blob(b), blob(f))} lines, upstream +-{diffsz(blob(b), blob(n))} lines, {conflicts(p, b, f, n)} conflict hunk(s)"
        rows[k].append((p, extra))
    out = ['# Renderer migration analysis (generated by android/render/migrate.py)', '',
           f'BASE `{BASE}` = {git("rev-parse", BASE).strip()}', f'THEIRS `{THEIRS}` = {git("rev-parse", THEIRS).strip()}', '']
    for k, v in rows.items():
        out += [f'## {k}: {len(v)} files', '']
        if k.startswith('changed on both') or len(v) <= 40:
            out += [f'- `{p}` {e}'.rstrip() for p, e in v]
        else: out += [f'- (first 12) ' + ', '.join(f'`{p}`' for p, _ in v[:12]) + ', ...']
        out.append('')
    open(os.path.join(ROOT, 'android', 'render', 'MIGRATION_ANALYSIS.md'), 'w').write('\n'.join(out))
    print('\n'.join(out[:6])); print({k: len(v) for k, v in rows.items()})
if __name__ == '__main__': main()
