"""Embed SMAA (libs/video/third_party/smaa, MIT, iryoku/smaa) into the live
renderer: the HLSL source as a C string and the two lookup tables as bytes.

usage: python tools/embed_smaa.py
Writes libs/video/rsx_smaa_embed.inc. Run again if third_party/smaa changes.
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.normpath(os.path.join(here, "..", "libs", "video", "third_party", "smaa"))
out = os.path.normpath(os.path.join(here, "..", "libs", "video", "rsx_smaa_embed.inc"))

# The file is Latin-1 with a few non-ASCII characters, all in comments.
hlsl = open(os.path.join(src, "SMAA.hlsl"), encoding="latin-1").read().replace("\r\n", "\n")
hlsl = "".join(ch if ord(ch) < 128 else "?" for ch in hlsl)


def c_str(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"'


lines = [
    "/* GENERATED by tools/embed_smaa.py from libs/video/third_party/smaa",
    " * (SMAA by Jorge Jimenez et al., MIT licence: third_party/smaa/LICENSE.txt).",
    " * Do not edit; regenerate. */",
    "",
    "/* The SMAA HLSL library, compiled behind the renderer's own wrapper. One",
    " * literal per source line keeps every piece far below MSVC's limits. */",
    "static const char* const s_smaa_hlsl_lines[] = {",
]
for line in hlsl.split("\n"):
    lines.append("    " + c_str(line) + ",")
lines.append("};")
lines.append("")
lines.append('#include "third_party/smaa/AreaTex.h"')
lines.append('#include "third_party/smaa/SearchTex.h"')
lines.append("")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", out, len(hlsl), "bytes of HLSL")
